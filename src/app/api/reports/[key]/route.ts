import { NextResponse, type NextRequest } from "next/server";
import { getCurrentUser } from "@/server/auth";
import { audit } from "@/server/audit";
import { prisma } from "@/server/db";
import { canViewReport, getReport } from "@/server/reports";
import { runReport } from "@/server/reports/run";
import { cellText, CSV_ROW_LIMIT, type Filters } from "@/server/reports/types";
import { formatDateTime } from "@/lib/dates";
import { toCsv } from "@/lib/csv";

const FILTER_LABELS: Record<string, string> = {
  q: "Search",
  from: "From",
  to: "To",
  supplierId: "Supplier",
  materialId: "Material",
  unitId: "Unit",
  status: "Status",
  storeId: "Store",
  productId: "Product",
  sku: "SKU",
  txnType: "Type",
  ref: "Reference",
  categoryId: "Category",
  expiryStatus: "Expiry status",
  stockStatus: "Stock status",
  condition: "Condition",
  category: "Document type",
};

/** Human-readable filter summary: record IDs are replaced by their names. */
async function describeFilters(filters: Filters) {
  const name = async (k: string, v: string) => {
    switch (k) {
      case "storeId":
        return (await prisma.store.findUnique({ where: { id: v } }))?.name ?? v;
      case "productId": {
        const p = await prisma.readyProduct.findUnique({ where: { id: v } });
        return p ? `${p.name} (${p.sku})` : v;
      }
      case "supplierId":
        return (await prisma.supplier.findUnique({ where: { id: v } }))?.name ?? v;
      case "materialId":
        return (await prisma.rawMaterial.findUnique({ where: { id: v } }))?.name ?? v;
      case "unitId":
        return (await prisma.unit.findUnique({ where: { id: v } }))?.code ?? v;
      case "categoryId":
        return (await prisma.productCategory.findUnique({ where: { id: v } }))?.name ?? v;
      default:
        return v;
    }
  };
  const parts = await Promise.all(
    Object.entries(filters)
      .filter(([, v]) => v)
      .map(async ([k, v]) => `${FILTER_LABELS[k] ?? k}: ${await name(k, v!)}`),
  );
  return parts.join("; ");
}

export async function GET(req: NextRequest, { params }: { params: Promise<{ key: string }> }) {
  const actor = await getCurrentUser();
  if (!actor) return NextResponse.json({ error: "Unauthenticated" }, { status: 401 });
  const { key } = await params;
  const def = getReport(key);
  if (!def) return NextResponse.json({ error: "Unknown report" }, { status: 404 });
  if (!canViewReport(actor, def)) return NextResponse.json({ error: "Forbidden" }, { status: 403 });

  const query = Object.fromEntries(req.nextUrl.searchParams.entries());
  const { result, filters, settings } = await runReport(def, query, { all: true });
  const columns = def.columns;
  const meta: unknown[][] = [
    ["Report", def.title],
    ["Generated", `${formatDateTime(new Date(), settings.timezone, settings.dateFormat)} (${settings.timezone})`],
    ["Generated by", actor.name],
    ["Filters", (await describeFilters(filters)) || "None"],
    [
      "Rows",
      result.total > CSV_ROW_LIMIT
        ? `${CSV_ROW_LIMIT} of ${result.total} (narrow the filters to export everything)`
        : String(result.rows.length),
    ],
    [],
  ];
  const body = toCsv([...meta, columns.map((c) => c.label), ...result.rows.map((r) => columns.map((c) => cellText(r[c.key])))]);
  await audit(prisma, {
    actorId: actor.id,
    action: "report.export",
    entityType: "Report",
    entityId: def.key,
    summary: `Exported ${def.title} (${result.rows.length} rows)`,
    details: filters,
  });

  const stamp = new Date().toISOString().slice(0, 10);
  return new NextResponse(body, {
    headers: {
      "Content-Type": "text/csv; charset=utf-8",
      "Content-Disposition": `attachment; filename="shayvera-${def.key}-${stamp}.csv"`,
      "Cache-Control": "private, no-store",
    },
  });
}
